n = int(input("Введите число, большее 30: ")) #Считываем число из консоли

while n <= 30: #Если введённое число не подходит по условию, просим ввести ещё раз,
               #пока не получим нужное
    print("Число не подходит") #Печатаем предупреждение, что число не подошло
    n = int(input("Введите другое число: ")) #Просим повторно ввести число


L = [i for i in range(n + 1)] #Создаём список чисел до n включительно

for i in range(2, int(n ** 0.5) + 1): #Достаточно пройти только по квадратному корню n чисел,
                                      #потому что числа, больше этого корня уже будут отброшены
    if L[i] != None: #Если число простое, удаляем все большие числа, которые делятся на данное число
        for j in range(i * i, n + 1, i): #Отбрасываем числа, делящиеся на данное число
            L[j] = None


M = [el for el in L[2:] if el != None] #Создаём список простых чисел, отбрасывая 0 и 1,
                                       #так как они не являются простыми
print(M) #Выводим ответ