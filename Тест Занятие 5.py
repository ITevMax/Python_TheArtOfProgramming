def square(M, y = 0, x = 0, L = None, S = None):                #Создание функции по поиску максимального квадрата матрицы, заполненного нулями. Некоторые поля заполнены значениями по умолчанию
    if L is None:                                               #Если размер матрицы не указан
        L = len(M)                                              #Заполняем самостоятельно
        S={}                                                    #И создаём словарь для кэширования
    
    if (y, x, L) not in S:                                      #Если нет такого ключа в словаре (не происходил поиск по таким условиям)
        f = True                                                #Ставим флаг по умолчанию True
        for i in range(y, y + L):                               #Цикл по строкам
            for j in range(x, x + L):                           #Цикл по колонкам
                if M[i][j] != 0:                                #Если элемент не является нулём
                    f = False                                   #Записываем во флаг ложное значение
                    break                                       #И выходим из цикла
            
            if f == False:                                      #Если флаг выдаёт ложь, то выходим из внешнего цикла
                break
        
        if f:                                                   #Если же мы вышли из цикла с флагом со значением True
            S[y,x,L] = L                                        #Записываем максимальный размер квадратной матрицы с нулями в данными значениями полей
        else:
            S[y, x, L] = max(square(M, y + 1, x + 1, L - 1, S), #Иначе, ищем другие матрицы поменьше со смещением и без и берём максимально большой из вычисленных
                            square(M, y + 1, x, L - 1, S),
                            square(M, y, x + 1, L - 1, S),
                            square(M, y, x, L - 1, S))
    
    return S[y, x, L]                                           #Есил же есть в словаре данные переметры, то возвращаем размер максимального квадрата матрицы


