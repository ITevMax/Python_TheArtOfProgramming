def simple(n : int) -> int:                 #Функция, которая возвращает просто число, без преобразований
    return n

def multiply_in_range(n : int, f) -> int:   #Функция, которая возвращает произведение значений функции от 1 до n
    s = 1                                   #Устанавливаем 1, так как на 0 умножать бесмысленно
    for i in range(1, n + 1):               #Цикл для передачи аргументов в переданную функцию
        s *= f(i)                           #Произведение возвращённых результатов функции с переданным аргументом
    return s

def fact(n : int) -> int:                                
    return multiply_in_range(n, simple)     

def sum_in_range(n : int, f) -> int:        #Функция, которая возвращает сумму значений функции от 1 до n
    s = 0
    for i in range(1, n + 1):               #Цикл для передачи аргументов в переданную функцию
        s += f(i)                           #Сумма возвращённых результатов функции с переданным аргументом
    return s

n = int(input())                            #Чтение числа
print(sum_in_range(n, fact))                #Вывод результата суммы факториалов
#Для входного значения 15 будет выведено 153