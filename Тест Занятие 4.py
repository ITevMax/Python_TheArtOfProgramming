F = {} #Создание словаря. Он нужен для оптимизации, так как работает быстрее списков

def fib(n : int) -> int: #Создание функции для поиска числа Фибоначчи
    if n not in F: #Если число ещё не было посчитано...
        if n <= 2: #И число меньше или равно 2
            F[n] = 1 #Число Фибоначчи будет единицией (по условию последовательности Фибоначчи)
        else:
            F[n] = fib(n - 2) + fib(n - 1) #Иначе, запишем это число по определению числа Фибоначчи
    return F[n] #Если число уже есть в словаре, возвращаем сохранённое значение

print(fib(8)) #Вывод результатов
print(fib(12))
print(fib(16))