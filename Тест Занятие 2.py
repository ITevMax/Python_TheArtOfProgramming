string = input("Введите строку: ") #Чтение строки пользователя

palindrome = "" #Задаём пустую строку для палиндрома
middleLetter = "" #Задаём пустую строку для буквы посередине палиндрома.
                  #Если во входной строке будет символ, введённый нечётное количество раз,
                  #то он будет посередине палиндрома, иначе просто добавится пустая строка
for letter in set(string): #Цикл, который по одному разу будет получать каждый символ на вход
    if string.count(letter) % 2 == 1: #Если символ в строке встречается нечётное количество раз,
                                      #то он записывается, как средняя буква палиндрома
        middleLetter = letter
    palindrome += letter * (string.count(letter) // 2) #В конец строки записывается половина символов палиндрома

palindrome += middleLetter + palindrome[::-1] #Формируем палиндром до конца, добавляя среднюю букву
                                              #и добавляя развёрнутую половину записанной части палиндрома

print("Палиндром максильной длины из входной строки: " + palindrome) #Вывод ответа