class point:                            #Создание класса
    def __init__(self, x = 0, y = 0):   #При создании объекта вызывается этот метод.
                                        #По умолчанию x и y равны 0, чтобы можно было
                                        #через input с консоли взять значения
        self.x = x                      #Привязка значения x к полю x объекта
        self.y = y                      #Привязка значения y к полю y объекта
    def input(self):                    #Метод для ввода значений x и y из консоли
        s = input().split()             #Чтение ввода и разбиение на x и y
        self.x = float(s[0])            #Привязки значений к полям
        self.y = float(s[1])
        return self                     #Возвражение нового объекта point со своими значениями полей

def dist(A : point, B : point):         #Метод для подсчёта расстояния между точками (По теореме Пифагора)
    return round(((B.x - A.x) ** 2 + (B.y - A.y) ** 2) ** 0.5, 3)   #Метод с округлением до 3 цифр после запятой

A = point().input()                     #Создание точек с вводом значений полей с консоли
B = point().input()
print(dist(A, B))                       #Вывод результата
