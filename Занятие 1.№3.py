a = float(input())  #Ввод сторон треугольника
b = float(input())
c = float(input())
a, b, c = sorted([a,b,c])

'''Создаём отсортированный список, чтобы сравнение происходило проще
(Максимальная сторона в конце, а минимальная - в начале)'''

if a + b > c: #Сумма двух меньших сторон должна быть больше большей стороны.
    print("Треугольник существует")
    if a == c: #Если сторона в начале списка равна конечной, значит и
                    #стороная "посередине" равна остальным
        print("Треугольник является равносторонним")
    elif a==b or b==c: #Проверка на равенство двух сторон
        print("Треугольник является равнобедренным")
    else: #Если нет равных сторон, треугольник разносторонний
        print("Треугельник является разносторонним")
else:
    print("Такой трекгольник не существует") #Если большая сторона больше суммы меньших